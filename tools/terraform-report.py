#!/usr/bin/env python3
"""Report Terraform lifecycle metadata; never invokes Terraform or reads its files."""
import argparse
import datetime
import hashlib
import hmac
import json
import os
import pathlib
import re
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
import uuid


class NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        return None


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run-id", required=True, type=uuid.UUID)
    parser.add_argument("--operation", required=True, choices=["plan", "apply", "destroy"])
    parser.add_argument("--phase", required=True, choices=["started", "completed"])
    parser.add_argument("--exit-code", type=int)
    parser.add_argument("--occurred-at", help="Original ISO timestamp for a delayed retry")
    parser.add_argument("--actor", default=os.environ.get("GITHUB_ACTOR"))
    parser.add_argument("--commit", default=os.environ.get("GITHUB_SHA"))
    parser.add_argument("--repository", default=os.environ.get("GITHUB_REPOSITORY"))
    parser.add_argument("--github-run-id", default=os.environ.get("GITHUB_RUN_ID"))
    parser.add_argument("--trigger", choices=["cli", "push", "pull_request", "manual", "schedule", "api", "unknown"])
    args = parser.parse_args()
    if ((args.phase == "completed") != (args.exit_code is not None)
            or args.exit_code is not None and not 0 <= args.exit_code <= 255):
        parser.error("Only completed reports require --exit-code (0..255)")
    url = os.environ.get("AFE_TERRAFORM_REPORT_URL", "")
    parsed = urllib.parse.urlsplit(url)
    loopback = parsed.hostname in ("localhost", "127.0.0.1", "::1")
    if (parsed.scheme != "https" and not (parsed.scheme == "http" and loopback)
            or not parsed.hostname or parsed.username or parsed.password or parsed.query or parsed.fragment
            or not re.fullmatch(r"/agent/terraform/v1/[a-fA-F0-9-]{36}/reports", parsed.path)):
        parser.error("AFE_TERRAFORM_REPORT_URL must be an HTTPS reporter endpoint (HTTP only on loopback)")
    secret = os.environ.get("AFE_TERRAFORM_SECRET")
    secret_file = os.environ.get("AFE_TERRAFORM_SECRET_FILE")
    if bool(secret) == bool(secret_file):
        parser.error("Set exactly one of AFE_TERRAFORM_SECRET or AFE_TERRAFORM_SECRET_FILE")
    if secret_file:
        secret = pathlib.Path(secret_file).read_text().strip()
    if not secret or not re.fullmatch(r"[a-f0-9]{64}", secret):
        parser.error("Expected the 64-character reporter secret generated by Afe")
    stamp = lambda: datetime.datetime.now(datetime.timezone.utc).isoformat()
    trigger = args.trigger or {"push": "push", "pull_request": "pull_request",
                              "workflow_dispatch": "manual", "schedule": "schedule",
                              "repository_dispatch": "api"}.get(os.environ.get("GITHUB_EVENT_NAME"),
                                                                "unknown" if os.environ.get("GITHUB_EVENT_NAME") else "cli")
    occurred_at = args.occurred_at or stamp()
    if args.occurred_at:
        original = datetime.datetime.fromisoformat(args.occurred_at.replace("Z", "+00:00"))
        if original.tzinfo is None:
            parser.error("--occurred-at requires an ISO timestamp with a timezone")
    report = {"version": 1, "runId": str(args.run_id), "operation": args.operation,
              "phase": args.phase, "occurredAt": occurred_at, "trigger": trigger}
    for key, value in [("exitCode", args.exit_code), ("actor", args.actor), ("commitSha", args.commit),
                       ("repository", args.repository), ("githubRunId", args.github_run_id)]:
        if value is not None:
            report[key] = value
    opener = urllib.request.build_opener(NoRedirect)
    for attempt in range(3):
        # Only sentAt changes on retries; the source event key and occurredAt stay stable.
        report["sentAt"] = stamp()
        body = json.dumps(report, separators=(",", ":")).encode()
        signature = "sha256=" + hmac.new(secret.encode(), body, hashlib.sha256).hexdigest()
        request = urllib.request.Request(url, body, {"Content-Type": "application/json", "X-Afe-Signature": signature})
        try:
            with opener.open(request, timeout=10) as response:
                result = json.loads(response.read(1024))
                if result.get("status") not in ("accepted", "duplicate"):
                    raise RuntimeError("Unexpected reporter response")
                print(f"Afe report {result['status']}: {args.operation} {args.phase}")
                return 0
        except urllib.error.HTTPError as error:
            if error.code != 429 and error.code < 500:
                print(f"Afe rejected report (HTTP {error.code}); check connection, secret and metadata.", file=sys.stderr)
                return 1
        except (OSError, ValueError, RuntimeError):
            pass
        if attempt < 2:
            time.sleep(2 ** attempt)
    print(f"Afe report was not acknowledged; Terraform's result is unchanged. Retry with the same run ID and --occurred-at {occurred_at}.", file=sys.stderr)
    return 1


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (OSError, ValueError):
        # No paths, network response bodies, file contents or credential values.
        print("Could not read reporter configuration or send metadata.", file=sys.stderr)
        sys.exit(1)
